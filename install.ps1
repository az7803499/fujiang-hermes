<#
  install.ps1 — 把富江人格装进 hermes-agent
  用法：
    .\install.ps1            # 真装
    .\install.ps1 -DryRun    # 只打印将要做的事
    .\install.ps1 -Mode Soul # 只装 SOUL.md（全局身份，推荐）
    .\install.ps1 -Mode Personality # 只注册 /personality fujiang
    .\install.ps1 -Mode Both        # 两个都装（默认）

  做三件事：
    1. 备份现有 SOUL.md（SOUL.md.bak-<时间戳>），再写入新的 SOUL.md
    2. 在 config.yaml 里注册 agent.personalities.fujiang
    3. 回读两个文件，打印校验结果
#>
[CmdletBinding()]
param(
  [ValidateSet('Soul','Personality','Both')]
  [string]$Mode = 'Both',
  [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$srcDir = Split-Path -Parent $MyInvocation.MyCommand.Path

# ---------- 1. 定位 HERMES_HOME ----------
if ($env:HERMES_HOME) { $hermesHome = $env:HERMES_HOME }
elseif ($env:LOCALAPPDATA) { $hermesHome = Join-Path $env:LOCALAPPDATA 'hermes' }
else { throw '找不到 LOCALAPPDATA，请手动指定：$env:HERMES_HOME = "D:\hermes"' }

Write-Host "[i] HERMES_HOME = $hermesHome"
if (-not (Test-Path -LiteralPath $hermesHome)) {
  if ($DryRun) { Write-Host "[dry] 会创建目录 $hermesHome" }
  else { New-Item -ItemType Directory -Path $hermesHome -Force | Out-Null; Write-Host "[+] 已创建 $hermesHome" }
}

$soulPath   = Join-Path $hermesHome 'SOUL.md'
$configPath = Join-Path $hermesHome 'config.yaml'
$stamp      = Get-Date -Format 'yyyyMMdd-HHmmss'

# ---------- 2. 装 SOUL.md ----------
if ($Mode -in 'Soul','Both') {
  $srcSoul = Join-Path $srcDir 'SOUL.md'
  if (-not (Test-Path -LiteralPath $srcSoul)) { throw "找不到 $srcSoul" }

  if (Test-Path -LiteralPath $soulPath) {
    $bak = "$soulPath.bak-$stamp"
    if ($DryRun) { Write-Host "[dry] 会备份 $soulPath -> $bak" }
    else { Copy-Item -LiteralPath $soulPath -Destination $bak -Force; Write-Host "[+] 已备份 $bak" }
  }

  if ($DryRun) {
    Write-Host "[dry] 会写入 $soulPath（$((Get-Item -LiteralPath $srcSoul).Length) 字节）"
  } else {
    Copy-Item -LiteralPath $srcSoul -Destination $soulPath -Force
    Write-Host "[+] 已写入 $soulPath"
  }
}

# ---------- 3. 注册 personalities ----------
function Get-PersonalityBlock {
  $lines = Get-Content -LiteralPath (Join-Path $srcDir 'config-snippet.yaml') -Encoding UTF8
  # 取 fujiang: | 之后的所有 6 空格缩进行，重新缩进到 6 空格
  $body = @()
  $in = $false
  foreach ($l in $lines) {
    if ($l -match '^\s*fujiang:\s*\|') { $in = $true; continue }
    if ($in) {
      if ($l -match '^\s{6,}\S') { $body += '      ' + $l.TrimStart() }
      elseif ($l.Trim() -eq '') { continue }
      else { break }
    }
  }
  return ,$body
}

if ($Mode -in 'Personality','Both') {
  $body = Get-PersonalityBlock
  if (-not $body -or $body.Count -eq 0) { throw 'config-snippet.yaml 里没解析到 fujiang 人格正文' }

  if (-not (Test-Path -LiteralPath $configPath)) {
    $out = @('# hermes config — generated by fujiang install.ps1', 'agent:', '  personalities:', '    fujiang: |') + $body
    if ($DryRun) { Write-Host "[dry] 会新建 $configPath（$($out.Count) 行）" }
    else {
      Set-Content -LiteralPath $configPath -Value $out -Encoding UTF8
      Write-Host "[+] 已新建 $configPath"
    }
  }
  else {
    $cfg = Get-Content -LiteralPath $configPath -Encoding UTF8
    if ($cfg -match '^\s*personalities:\s*$' -or $cfg -match '^\s*personalities:\s*\{') {
      Write-Host "[!] $configPath 里已经有 personalities: 段，未自动改动。"
      Write-Host "    请手动把下面这条加进那个段里（缩进 4 格）："
      Write-Host ''
      Write-Host '    fujiang: |'
      $body | ForEach-Object { Write-Host $_ }
      Write-Host ''
    }
    else {
      $block = @('  personalities:', '    fujiang: |') + $body
      $agentIdx = -1
      for ($i = 0; $i -lt $cfg.Count; $i++) { if ($cfg[$i] -match '^agent:\s*$') { $agentIdx = $i; break } }

      if ($agentIdx -ge 0) {
        $new = @()
        $new += $cfg[0..$agentIdx]
        $new += $block
        if ($agentIdx + 1 -le $cfg.Count - 1) { $new += $cfg[($agentIdx + 1)..($cfg.Count - 1)] }
      } else {
        $new = @($cfg) + @('', 'agent:') + $block
      }

      $bak = "$configPath.bak-$stamp"
      if ($DryRun) {
        Write-Host "[dry] 会备份 $configPath -> $bak"
        Write-Host "[dry] 会插入 $($block.Count) 行到 agent: 段下"
      } else {
        Copy-Item -LiteralPath $configPath -Destination $bak -Force
        Write-Host "[+] 已备份 $bak"
        Set-Content -LiteralPath $configPath -Value $new -Encoding UTF8
        Write-Host "[+] 已写入 $configPath"
      }
    }
  }
}

# ---------- 4. 回读校验 ----------
Write-Host ''
Write-Host '--- 校验 ---'
if (Test-Path -LiteralPath $soulPath) {
  $sz = (Get-Item -LiteralPath $soulPath).Length
  $head = (Get-Content -LiteralPath $soulPath -Encoding UTF8 -TotalCount 1)
  Write-Host ("SOUL.md      : {0} 字节  首行: {1}" -f $sz, $head)
}
if (Test-Path -LiteralPath $configPath) {
  $hit = Select-String -LiteralPath $configPath -Pattern 'fujiang:' -SimpleMatch
  if ($hit) { Write-Host ("config.yaml  : 第 {0} 行找到 fujiang:" -f $hit[0].LineNumber) }
  else { Write-Host 'config.yaml  : 未找到 fujiang:（personalities 分支可能被跳过）' }
}
Write-Host ''
Write-Host '下一步：'
Write-Host '  hermes doctor'
Write-Host '  hermes chat -q "富江"      # 应只回「富江」两个字'
if ($Mode -in 'Personality','Both') {
  Write-Host '  hermes                     # 进交互后：/personality fujiang'
}
